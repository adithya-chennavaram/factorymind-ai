"""Offline audit of predicted-healthy reviews; NEVER use labels to decide whom to review.

Input must be blocked predictions with out-of-fold P(Optimal) generated by
`python -m factorymind.train`; results are experimental test-rig only.
"""
import argparse
import json
from pathlib import Path
import numpy as np
import pandas as pd

REQUIRED = {"cycle_id", "actual", "predicted", "fold", "p_optimal_uncalibrated"}


def evaluate(df, budgets=(10, 20, 30)):
    if not REQUIRED.issubset(df.columns):
        missing = sorted(REQUIRED - set(df.columns))
        raise ValueError("Missing out-of-fold probability columns; retrain once to create them: " + ", ".join(missing))
    if df.cycle_id.duplicated().any() or df.p_optimal_uncalibrated.isna().any():
        raise ValueError("Duplicate cycle IDs or missing probabilities")
    if not df.p_optimal_uncalibrated.between(0, 1).all():
        raise ValueError("Probabilities outside [0,1]")
    green = df[df.predicted == 100].copy()
    green["incorrect_green"] = green.actual != 100
    if green.empty:
        raise ValueError("No predicted optimal cases")
    results = []
    for budget in budgets:
        rows = []
        for fold, group in green.groupby("fold", sort=True):
            n = len(group)
            k = int(np.floor(n * budget / 100))
            flagged = group.sort_values(["p_optimal_uncalibrated", "cycle_id"], kind="stable").head(k)
            total_missed = int(group.incorrect_green.sum())
            caught = int(flagged.incorrect_green.sum())
            rows.append({"fold": int(fold), "predicted_green": n, "false_green": total_missed,
                         "reviewed": k, "false_green_caught": caught,
                         "false_green_missed": total_missed - caught,
                         "random_expected_caught": k * total_missed / n})
        caught = sum(r["false_green_caught"] for r in rows)
        errors = sum(r["false_green"] for r in rows)
        reviewed = sum(r["reviewed"] for r in rows)
        results.append({"review_budget_pct_of_predicted_green_per_fold": budget,
                        "reviewed": reviewed, "false_green_caught": caught,
                        "false_green_catch_rate": round(caught/errors, 4) if errors else None,
                        "inspection_precision": round(caught/reviewed, 4) if reviewed else None,
                        "random_expected_caught": round(sum(r["random_expected_caught"] for r in rows), 2),
                        "false_green_remaining_unreviewed": errors - caught, "folds": rows})
    return {"scope": "experimental cycles, purged blocked out-of-fold predictions",
            "methods": "Within each held-out fold, sort predicted-green cases by lowest out-of-fold P(Optimal). Thresholds set by review capacity only; labels are used only after selecting cases for evaluation.",
            "limitation": "Uncalibrated probabilities; baseline policy only. No claim of prevented failures or measured improvement over an independent guardian.",
            "all_cycles": int(len(df)), "predicted_green": int(len(green)),
            "false_green": int(green.incorrect_green.sum()), "budgets": results}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=Path("artifacts/blocked_predictions.csv"))
    parser.add_argument("--output", type=Path, default=Path("artifacts/green_review_baseline.json"))
    args = parser.parse_args()
    report = evaluate(pd.read_csv(args.input))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2))
    print(json.dumps({"predicted_green":report["predicted_green"], "false_green":report["false_green"],
                      "budget_summaries": [{k: v for k,v in row.items() if k != "folds"} for row in report["budgets"]]}, indent=2))

if __name__ == "__main__":
    main()
